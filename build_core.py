def ld(obj): return '\n  <script type="application/ld+json">\n%s\n  </script>' % json.dumps(obj, ensure_ascii=False, indent=2)

def apply(lang, fname):
    path = ('ua/' if lang == 'ua' else '') + fname
    s = open(path, encoding='utf-8').read()
    pre = '../' if lang == 'ua' else ''
    s = re.sub(r'\n?<!-- cw:extra -->.*?<!-- /cw:extra -->\n?', '\n', s, flags=re.S)
    extra = '<!-- cw:extra -->\n' + ''.join(PAGES[(lang, fname)]()) + '<!-- /cw:extra -->\n'
    m = re.search(r'\n[ \t]*<section class="order-band"', s)
    if m: s = s[:m.start()] + '\n' + extra + s[m.start():]
    else:
        i = s.rfind('</main>'); s = s[:i] + extra + s[i:]
    if 'css/blocks.css' not in s:
        s = re.sub(r'(<link rel="stylesheet" href="[^"]*tokens\.css">)', lambda x: x.group(1) + '\n  ' + BLOCKS_LINK % pre, s, 1)
    # JSON-LD: replace any FAQPage block with fresh one built from visible FAQ
    s = re.sub(r'\s*<script type="application/ld\+json">\s*\{[^<]*"@type":\s*"FAQPage".*?</script>', '', s, flags=re.S)
    faq = FAQ[(lang, fname)]
    s = s.replace('</head>', ld({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq]}) + '\n</head>', 1)
    open(path, 'w', encoding='utf-8').write(s)


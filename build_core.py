def faq_html(items, heading):
    out = '<section class="cw-block cw-faq"><h2>%s</h2>\n' % heading
    for q, a in items:
        out += '  <details><summary>%s</summary><p>%s</p></details>\n' % (q, a)
    return out + '</section>\n'

def steps_html(heading, steps):
    out = '<section class="cw-block"><h2>%s</h2>\n<ol class="cw-steps">\n' % heading
    for t, d in steps: out += '  <li><strong>%s</strong>%s</li>\n' % (t, d)
    return out + '</ol></section>\n'

def table_html(heading, cols, rows, note):
    out = '<section class="cw-block"><h2>%s</h2>\n<table class="cw-price-table"><thead><tr>' % heading
    out += ''.join('<th scope="col">%s</th>' % c for c in cols) + '</tr></thead><tbody>\n'
    for r in rows:
        out += '<tr><td data-label="%s">%s</td><td class="cw-price" data-label="%s">%s</td><td data-label="%s">%s</td></tr>\n' % (cols[0], r[0], cols[1], r[1], cols[2], r[2])
    out += '</tbody></table>\n'
    if note: out += '<p class="cw-note">%s</p>\n' % note
    return out + '</section>\n'

def text_html(heading, paras):
    return '<section class="cw-block"><h2>%s</h2>\n%s</section>\n' % (heading, ''.join('<p>%s</p>\n' % p for p in paras))

def why_html(heading, items):
    out = '<section class="cw-block"><h2>%s</h2>\n<ul class="cw-why">\n' % heading
    for ico, t, d in items: out += '  <li><span class="cw-ico" aria-hidden="true">%s</span><strong>%s</strong>%s</li>\n' % (ico, t, d)
    return out + '</ul></section>\n'

def reviews_html(heading, items, label):
    out = '<section class="cw-block"><h2>%s</h2>\n<div class="cw-reviews" tabindex="0" role="region" aria-label="%s">\n' % (heading, label)
    for q, who in items: out += '  <figure><blockquote>%s</blockquote><figcaption>%s</figcaption></figure>\n' % (q, who)
    return out + '</div></section>\n'

def map_html(heading, addr_lines, iframe_src, title):
    return ('<section class="cw-block"><h2>%s</h2>\n<div class="cw-map"><address>%s</address>\n'
            '<iframe title="%s" src="%s" loading="lazy" referrerpolicy="no-referrer-when-downgrade"></iframe></div></section>\n') % (heading, '<br>'.join(addr_lines), title, iframe_src)

